// 커밋해 둔 결과·논문 폴더(사용자 결정 「적용 때 물어보기」, 2026-11-13 — 역할극 11 회차 M3·M5).
// 벤치 결과 숫자(bench-results/)·논문 원고(paper/*.tex·refs.bib)·그림 원자료(paper/figures/runs.txt)는 Claude 가 손으로 고치면 안 되지만,
// git 이 추적하는 파일이라 .gitignore 단서(suggest.mjs protect)의 범위 밖이었다. 말없이 넣지 않는다 — 보호할지 적용 때 묻는다
// (ROS 2 관절 한계·URDF 와 같은 길: setup 스킬이 묻고, 「예」면 protected-files paths 에 넣는다).
// 지어내지 않는다: git 이 추적하는 파일이 실제로 든 폴더만. 소스 코드가 섞인 폴더는 폴더째 내지 않는다.
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { readText, filesIn } from './stack-scan.mjs';

// 결과 폴더 이름(맨 위 기준). 데이터·문서 파일만 들어 있을 때만
const RESULT_DIRS = ['results', 'bench-results', 'benchmark-results', 'benchmarks/results', 'bench/results', 'experiments/results'];
// 논문 폴더 이름. .tex·.bib 가 있을 때만
const PAPER_DIRS = ['paper', 'papers', 'manuscript', 'thesis'];
// 맨 위 figures/ 는 근거(스크립트가 그 폴더에 쓰거나 .gitignore 주석이 말함)가 있을 때만 — 문서용 그림 폴더일 때가 많다
const FIGURE_DIR = 'figures';
// 기록한 결과로 볼 파일(표·숫자·그림·설명). 모르는 확장자가 하나라도 있으면 폴더째 내지 않는다(지키는 쪽보다 헛물음을 피한다)
const DATA_EXT = /\.(?:csv|tsv|txt|json|jsonl|ndjson|dat|parquet|feather|npz|npy|h5|hdf5|xlsx|md|rst|ya?ml|png|jpe?g|svg|pdf|eps|gif)$/i;
// 숫자를 적은 글 파일(그림 원자료) — 그림 파일은 스크립트가 다시 만드는 결과라 하나씩 내지 않는다
const TEXT_DATA = /\.(?:csv|tsv|txt|json|jsonl|dat)$/i;
const PAPER_EXT = /\.(?:tex|bib|cls|sty|bst|bbx|cbx)$/i;
const PLAIN = /(?:^|\/)(?:README|LICENSE|NOTICE)[^/]*$|(?:^|\/)\.gitkeep$/i;
// 근거를 찾을 스크립트(맨 위·scripts/·bin/ 의 셸·파이썬·R·Julia 와 Makefile)
const SCRIPT = /\.(?:sh|bash|py|r|jl)$/i;
const FIGURE_DATA_MAX = 4; // 그림 원자료 파일은 하나씩 내니 몇 개까지만
const OFFER_MAX = 8;

// 추적 중인 파일 전부(한 번) — 논문 폴더가 저장소의 얼마인지, 시험이 어느 폴더를 읽는지 보려고
const tracked = (root) => {
  try {
    return execFileSync('git', ['-C', root, 'ls-files', '-z'],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 }).split('\0').filter(Boolean);
  } catch {
    return [];
  }
};
// 논문 폴더가 저장소의 절반을 넘으면 그 저장소 일이 원고 쓰기다(학위 논문 저장소) — 원고를 지키면 할 일을 막는다(검토 2026-11-13)
const PAPER_SHARE_MAX = 0.5;
// 웹사이트 저장소(개인 학술 사이트의 papers/*.bib 는 출판 목록 글이다 — 고치는 것이 일): 맨 위의 이 파일들
const SITE_FILES = ['index.html', '_config.yml', '_config.yaml', 'hugo.toml', 'hugo.yaml', 'hugo.json', '_quarto.yml', 'astro.config.mjs', 'docusaurus.config.js', 'mkdocs.yml', '.nojekyll'];
const isSite = (root, files) => files.some((f) => SITE_FILES.includes(f))
  || /^\s*gem\s+["'](?:jekyll|github-pages)["']/m.test(readText(path.join(root, 'Gemfile')))
  || (files.includes('config.toml') && files.some((f) => f.startsWith('content/')) && files.some((f) => f.startsWith('themes/') || f.startsWith('layouts/')));
// 시험 자료: 기대값 이름(expected·golden·snapshot)이거나, 시험 파일이 그 폴더를 적는 것(results/expected.txt 를 읽는 tests/test_x.py)
const FIXTURE_NAME = /(?:^|\/)(?:expected|golden|snapshots?|fixtures?)[^/]*$/i;
const TEST_FILE = /(?:^|\/)(?:tests?|__tests__|spec|specs)\/|(?:^|\/)test_[^/]+$|[._-](?:test|spec)\.[^/]+$|_test\.[^/]+$/i;
const TEST_READ_MAX = 60;
const under = (files, dir) => files.filter((f) => f.startsWith(`${dir}/`));
const reRaw = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// 글에 그 폴더 경로가 맨 위 기준 낱말로 나오는지(bench-results/…·"bench-results"·./results/·ROOT / "bench-results").
// 뒤에 / 나 따옴표가 와야 한다 — 글 속 낱말(「raw results are …」)은 아님. my-results/·benchmarks/results/(다른 폴더 아래) 도 아님
const mentions = (text, dir) => new RegExp(`(?:^|[\\s"'=(]|\\./)${reRaw(dir)}(?:/|["'])`, 'm').test(text);
const scripts = (root) => ['.', 'scripts', 'bin', 'tools'].flatMap((d) => filesIn(root, d).filter((f) => SCRIPT.test(f) || f === 'Makefile')
  .slice(0, 40).map((f) => (d === '.' ? f : `${d}/${f}`)));
// 근거: 그 폴더를 적은 스크립트(run_bench.sh → bench-results/), 아니면 .gitignore 주석(「generated by paper/figures/plot.py」)
const evidence = (root, dir, list) => {
  const script = list.find((rel) => !rel.startsWith(`${dir}/`) && mentions(readText(path.join(root, rel)).slice(0, 64 * 1024), dir));
  if (script) return script;
  const note = readText(path.join(root, '.gitignore')).split(/\r?\n/).some((l) => l.trim().startsWith('#') && mentions(l, dir));
  return note ? '.gitignore' : null;
};

// → [{ v: 'bench-results/', k: 'results', at: 'scripts/run_bench.sh' }, { v: 'paper/**/*.tex', k: 'paper' }, { v: 'paper/figures/runs.txt', k: 'figure-data', at: 'paper/figures/plot.py' }]
export const recordOffers = (root) => {
  const files = tracked(root);
  if (!files.length) return [];
  const list = scripts(root);
  const out = [];
  // why 의 k·at(화면 문구 srcWhy_<k>): 근거가 스크립트면 그 파일, .gitignore 주석이면 -note, 근거 없이 이름·내용으로만 알면 -dir
  const push = (v, k, at) => out.push({ v, k, ...(at ? { at } : {}) });
  const byEvidence = (v, k, at) => push(v, at === '.gitignore' ? `${k}-note` : at ? k : `${k}-dir`, at);
  const onlyData = (inDir, ext) => inDir.every((f) => ext.test(f) || PLAIN.test(f)) && inDir.some((f) => !PLAIN.test(f) && !/\.(?:md|rst)$/i.test(f));
  // 시험 파일 글(결과 폴더 후보가 있을 때만 읽는다)
  let tests = null;
  const testsMention = (dir) => (tests ??= files.filter((f) => TEST_FILE.test(f) && !RESULT_DIRS.some((d) => f.startsWith(`${d}/`))).slice(0, TEST_READ_MAX)
    .map((f) => readText(path.join(root, f)).slice(0, 64 * 1024))).some((text) => mentions(text, dir));
  for (const dir of RESULT_DIRS) {
    const inDir = under(files, dir);
    if (!inDir.length || !onlyData(inDir, DATA_EXT)) continue;
    // 시험이 읽는 기대값 폴더는 결과 기록이 아니다(시험을 고치면 함께 고친다)
    if (inDir.some((f) => FIXTURE_NAME.test(f)) || testsMention(dir)) continue;
    byEvidence(`${dir}/`, 'results', evidence(root, dir, list));
  }
  const site = isSite(root, files);
  for (const dir of PAPER_DIRS) {
    const inDir = under(files, dir);
    const tex = inDir.filter((f) => /\.tex$/i.test(f));
    const bib = inDir.filter((f) => /\.bib$/i.test(f));
    if (!tex.length && !bib.length) continue;
    // 논문이 저장소의 대부분(학위 논문 저장소)이거나 웹사이트의 출판 목록이면 원고를 고치는 것이 일이다
    if (site || inDir.length > files.length * PAPER_SHARE_MAX) continue;
    const paperOrData = new RegExp(`${PAPER_EXT.source}|${DATA_EXT.source}`, 'i');
    // 원고·그림·자료만 든 폴더는 통째로. 그림을 만드는 코드(plot.py)가 섞이면 원고 파일과 그림 원자료만 — 코드까지 막으면 그림을 다시 못 만든다
    if (onlyData(inDir, paperOrData)) { push(`${dir}/`, 'paper'); continue; }
    if (tex.length) push(`${dir}/**/*.tex`, 'paper');
    if (bib.length) push(`${dir}/**/*.bib`, 'paper');
    // 그림 원자료: 같은 폴더의 스크립트가 그 파일 이름을 읽는 것만(plot.py 가 읽는 runs.txt)
    const code = inDir.filter((f) => SCRIPT.test(f)).map((c) => [c, readText(path.join(root, c)).slice(0, 64 * 1024)]);
    for (const f of inDir.filter((x) => TEXT_DATA.test(x) && !PLAIN.test(x))) {
      const reader = code.find(([c, text]) => path.posix.dirname(c) === path.posix.dirname(f) && text.includes(path.posix.basename(f)));
      if (reader) push(f, 'figure-data', reader[0]);
    }
  }
  // 맨 위 figures/: 그림·자료만 들었고 근거가 있을 때
  const figs = under(files, FIGURE_DIR);
  const figWhy = figs.length && onlyData(figs, DATA_EXT) ? evidence(root, FIGURE_DIR, list) : null;
  if (figWhy) byEvidence(`${FIGURE_DIR}/`, 'figures', figWhy);
  // 그림 원자료는 몇 개까지만(많으면 폴더 하나가 자리를 다 먹는다)
  let figureData = 0;
  return out.filter((x) => x.k !== 'figure-data' || ++figureData <= FIGURE_DATA_MAX).slice(0, OFFER_MAX);
};
