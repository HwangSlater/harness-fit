// 역할극 13 회차 4차(2026-11-13): overlap.mjs 가 모든 지침 묶음의 줄을 보여 줘 세션이 감지가 뺀 결제 묶음을 스스로 물었다 —
// 이 저장소가 받을 수 있는 묶음(어느 조합에든 든 것 + 감지한 스택에 딸린 것)과 지난번에 적용한 것만 보인다
test('겹침 견주기 목록: 결제 저장소가 아니면 결제 지침 줄을 보이지 않는다', async () => {
  const { overlapRuleIds } = await import('../overlap.mjs');
  const all = loadAll();
  const shop = { 'package.json': { dependencies: { next: '15', react: '19' } }, 'lib/payment.ts': '', 'app/checkout/page.tsx': '', 'app/api/checkout/route.ts': '' };
  const shopDet = detect(tracked(shop));
  const ids = overlapRuleIds(all, shopDet, null);
  assert.ok(!ids.includes('payments'), ids.join(','));
  assert.ok(['commands', 'lean', 'security', 'structure', 'collab'].every((id) => ids.includes(id)), '조합에 든 묶음은 그대로');
  assert.ok(ids.includes('github-flow'), '브랜치 방식 줄도 그대로');
  assert.ok(overlapRuleIds(all, shopDet, { selection: { rules: ['payments'] } }).includes('payments'), '지난번에 적용한 묶음은 보인다');
  const pay = { 'package.json': { dependencies: { express: '^4', stripe: '^17' } }, 'src/a.js': '' };
  assert.ok(overlapRuleIds(all, detect(tracked(pay)), null).includes('payments'), '결제 저장소면 보인다');
});
